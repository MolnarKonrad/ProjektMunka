package konrad.hu;

/**
 * A Displayable interfész definiálja a megjeleníthető objektumok
 * viselkedését. Az interfész tartalmaz egy metódust, amely lehetővé
 * teszi az objektumok információinak megjelenítését.
 */
public interface Displayable {

    /**
     * Megjeleníti az objektum információit.
     * Ezt a metódust a megjeleníthető objektumoknak kell implementálniuk.
     */
    void displayInfo();
}
